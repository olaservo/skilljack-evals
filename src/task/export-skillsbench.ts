/**
 * skilljack → SkillsBench/BenchFlow task-package exporter.
 *
 * Emits a BenchFlow-native package from one of our task packages so a task
 * can graduate to big containerized sweeps with one command:
 *
 *   task.md            their frontmatter shape (schema_version '1.3',
 *                      metadata/verifier/agent/environment blocks), prompt
 *                      body verbatim, plus an `x_skilljack:` block carrying
 *                      our checks/assertions/expectations so an import
 *                      round-trips losslessly
 *   environment/       skills under environment/skills/, our workspace seeds
 *                      under environment/workspace/, Dockerfile copied or a
 *                      node:20-slim stub generated
 *   verifier/test.sh   bash WRAPPER that runs our verify.* via the right
 *                      interpreter and writes /logs/verifier/reward.txt
 *                      (SkillsBench convention); lite-checks-only tasks get a
 *                      generated checks.mjs one-file checker instead
 *   oracle/solve.sh    wrapper around our solve.* (when an oracle exists)
 *
 * Host-only concepts cannot cross the boundary: tool_calls / no_tool_calls /
 * javascript checks and skill-activation expectations are dropped from the
 * generated verifier with a warning (they still round-trip via x_skilljack).
 */

import * as yaml from 'js-yaml';
import * as fs from 'fs/promises';
import * as path from 'path';
import { extractFrontmatterBlock, stripFrontmatter } from '../runner/skill-discovery.js';
import { copyDir } from '../run/workspace.js';
import type { TaskChecks } from './schema.js';

export interface ExportResult {
  /** Directory the BenchFlow-native package was written to. */
  outDir: string;
  warnings: string[];
}

export interface ExportOptions {
  /** Output directory (default: ./export/<task-id>). */
  outDir?: string;
}

async function isDirectory(p: string): Promise<boolean> {
  try {
    return (await fs.stat(p)).isDirectory();
  } catch {
    return false;
  }
}

async function isFile(p: string): Promise<boolean> {
  try {
    return (await fs.stat(p)).isFile();
  } catch {
    return false;
  }
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : undefined;
}

/** Find the first file in dir matching one of the prefixes (mirror of load.ts). */
async function findScript(dir: string, prefixes: string[]): Promise<string | undefined> {
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return undefined;
  }
  const files = entries.filter((e) => e.isFile()).map((e) => e.name).sort();
  for (const prefix of prefixes) {
    const match = files.find((f) => f.startsWith(`${prefix}.`));
    if (match) return path.join(dir, match);
  }
  return undefined;
}

/** Container interpreter for a script by extension (bash wrapper context). */
function wrapperInterpreter(fileName: string): string | undefined {
  const ext = path.extname(fileName).toLowerCase();
  switch (ext) {
    case '.mjs':
    case '.js':
      return 'node';
    case '.py':
      return 'python3';
    case '.sh':
      return 'bash';
    default:
      return undefined;
  }
}

/** Generate the bash wrapper that adapts our env contract to /logs/verifier/reward.txt. */
function buildShWrapper(kind: 'verifier' | 'oracle', interpreter: string, scriptName: string): string {
  const mountDir = kind === 'verifier' ? '/verifier' : '/oracle';
  const rewardLines = kind === 'verifier'
    ? `if [ -f "$SKILLJACK_REWARD_FILE" ]; then
  cp "$SKILLJACK_REWARD_FILE" /logs/verifier/reward.txt
elif [ $EXIT_CODE -eq 0 ]; then
  echo 1 > /logs/verifier/reward.txt
else
  echo 0 > /logs/verifier/reward.txt
fi
exit 0`
    : 'exit $EXIT_CODE';

  return `#!/bin/bash
# Generated by skilljack-evals export — wraps the skilljack ${kind} for the
# SkillsBench/BenchFlow convention${kind === 'verifier' ? ' (reward written to /logs/verifier/reward.txt)' : ''}.
mkdir -p /logs/verifier
export SKILLJACK_TASK_DIR="\${SKILLJACK_TASK_DIR:-/task}"
export SKILLJACK_OUTPUT_FILE="\${SKILLJACK_OUTPUT_FILE:-/logs/agent/output.txt}"
export SKILLJACK_TRAJECTORY_FILE="\${SKILLJACK_TRAJECTORY_FILE:-/logs/agent/trajectory.json}"
export SKILLJACK_REWARD_FILE="\${SKILLJACK_REWARD_FILE:-/tmp/skilljack-reward.txt}"
mkdir -p "$(dirname "$SKILLJACK_OUTPUT_FILE")" "$(dirname "$SKILLJACK_TRAJECTORY_FILE")"
[ -f "$SKILLJACK_OUTPUT_FILE" ] || : > "$SKILLJACK_OUTPUT_FILE"
[ -f "$SKILLJACK_TRAJECTORY_FILE" ] || echo '[]' > "$SKILLJACK_TRAJECTORY_FILE"
rm -f "$SKILLJACK_REWARD_FILE"
${interpreter} ${mountDir}/${scriptName}
EXIT_CODE=$?
${rewardLines}
`;
}

/** Generate a one-file node checker from lite checks (output-text + files_exist only). */
function buildChecksMjs(checks: TaskChecks): string {
  const portable = {
    contains: checks.contains ?? [],
    not_contains: checks.not_contains ?? [],
    regex: checks.regex ?? [],
    marker: checks.marker ?? null,
    files_exist: checks.files_exist ?? [],
  };
  return `// Generated by skilljack-evals export — lite deterministic checks compiled
// to a standalone verifier. Reads the agent output from SKILLJACK_OUTPUT_FILE
// (empty when the harness provides none) and checks workspace files relative
// to cwd (/workspace).
import { readFileSync, existsSync } from 'node:fs';

const CHECKS = ${JSON.stringify(portable, null, 2)};

let output = '';
try {
  output = readFileSync(process.env.SKILLJACK_OUTPUT_FILE, 'utf-8');
} catch {
  console.error('warning: no agent output file available — output-text checks run against an empty string');
}

const failures = [];
for (const s of CHECKS.contains) if (!output.includes(s)) failures.push(\`missing substring: \${s}\`);
for (const s of CHECKS.not_contains) if (output.includes(s)) failures.push(\`forbidden substring present: \${s}\`);
for (const p of CHECKS.regex) if (!new RegExp(p).test(output)) failures.push(\`regex did not match: \${p}\`);
if (CHECKS.marker && !output.toLowerCase().includes(CHECKS.marker.toLowerCase())) failures.push(\`missing marker: \${CHECKS.marker}\`);
for (const f of CHECKS.files_exist) if (!existsSync(f)) failures.push(\`missing file: \${f}\`);

if (failures.length > 0) {
  console.error('CHECKS FAILED:\\n- ' + failures.join('\\n- '));
  process.exit(1);
}
console.log('all checks passed');
`;
}

const DOCKERFILE_STUB = (hasWorkspace: boolean): string => `# Generated by skilljack-evals export — minimal environment stub.
# BenchFlow builds this image for the task; extend as the task requires.
FROM node:20-slim
WORKDIR /workspace
${hasWorkspace ? 'COPY workspace/ /workspace/\n' : ''}`;

/**
 * Export one of our task packages as a BenchFlow-native package.
 */
export async function exportSkillsBenchTask(taskDirInput: string, options: ExportOptions = {}): Promise<ExportResult> {
  const warnings: string[] = [];
  const taskDir = path.resolve(taskDirInput);
  const taskId = path.basename(taskDir);
  const taskMdPath = path.join(taskDir, 'task.md');

  if (!(await isFile(taskMdPath))) {
    throw new Error(`Not a task package: ${taskDirInput} (no task.md)`);
  }

  const outDir = path.resolve(options.outDir ?? path.join(process.cwd(), 'export', taskId));
  if (await isDirectory(outDir)) {
    throw new Error(`Export target already exists: ${outDir} — remove it or pass a different --out directory.`);
  }

  const content = await fs.readFile(taskMdPath, 'utf-8');
  const fmBlock = extractFrontmatterBlock(content);
  const fm: Record<string, unknown> = fmBlock !== null ? (asRecord(yaml.load(fmBlock)) ?? {}) : {};
  const body = stripFrontmatter(content).trim();
  const checks = asRecord(fm.checks) as TaskChecks | undefined;

  // --- Resolve package pieces on disk ---
  const verifierScript = await findScript(path.join(taskDir, 'verifier'), ['verify', 'test']);
  const oracleScript = await findScript(path.join(taskDir, 'oracle'), ['solve']);
  const envSkills = path.join(taskDir, 'environment', 'skills');
  const suiteSkills = path.join(path.dirname(taskDir), 'skills');
  const skillsDir = (await isDirectory(envSkills)) ? envSkills
    : (await isDirectory(suiteSkills)) ? suiteSkills : undefined;
  const workspaceSeed = path.join(taskDir, 'environment', 'workspace');
  const hasWorkspaceSeed = await isDirectory(workspaceSeed);
  const ownDockerfile = path.join(taskDir, 'environment', 'Dockerfile');

  // --- Build their frontmatter ---
  const verifierTimeoutMs = (asRecord(fm.verifier)?.timeout_ms as number | undefined) ?? 60000;
  const agentTimeoutMs = (fm.timeout_ms as number | undefined) ?? 300000;

  // Defaults matching the SkillsBench 1.3 shape; an x_skillsbench block from a
  // previous import restores the original values over these defaults.
  const restored = asRecord(fm.x_skillsbench) ?? {};
  const frontmatter: Record<string, unknown> = {
    schema_version: (restored.schema_version as string) ?? '1.3',
    metadata: {
      difficulty: (fm.difficulty as string) ?? 'medium',
      ...(fm.category !== undefined ? { category: fm.category } : {}),
      ...(fm.tags !== undefined ? { tags: fm.tags } : {}),
      ...(asRecord(restored.metadata) ?? {}),
    },
    verifier: {
      type: 'test-script',
      timeout_sec: verifierTimeoutMs / 1000,
      ...(asRecord(restored.verifier) ?? {}),
    },
    agent: {
      timeout_sec: agentTimeoutMs / 1000,
      ...(asRecord(restored.agent) ?? {}),
    },
    environment: asRecord(restored.environment) ?? {
      network_mode: 'none',
      build_timeout_sec: 600,
      os: 'linux',
      cpus: 1,
      memory_mb: 4096,
      storage_mb: 10240,
      gpus: 0,
    },
  };

  // Round-trip payload: our native scoring fields.
  const xSkilljack: Record<string, unknown> = {};
  if (fm.checks !== undefined) xSkilljack.checks = fm.checks;
  if (fm.assertions !== undefined) xSkilljack.assertions = fm.assertions;
  if (fm.expected_skill !== undefined) xSkilljack.expected_skill = fm.expected_skill;
  if (fm.expect_skill_invocation !== undefined) xSkilljack.expect_skill_invocation = fm.expect_skill_invocation;
  if (Object.keys(xSkilljack).length > 0) frontmatter.x_skilljack = xSkilljack;

  // Host-only checks that cannot run inside the exported verifier.
  const dropped: string[] = [];
  if (checks?.tool_calls) dropped.push('tool_calls');
  if (checks?.no_tool_calls) dropped.push('no_tool_calls');
  if (checks?.javascript) dropped.push('javascript');
  if (fm.expect_skill_invocation !== undefined) dropped.push('expect_skill_invocation');
  if (dropped.length > 0) {
    warnings.push(`host-only check concepts dropped from the exported verifier: ${dropped.join(', ')} (preserved in x_skilljack for round-trips)`);
  }

  // --- Write the package ---
  await fs.mkdir(outDir, { recursive: true });
  await fs.writeFile(
    path.join(outDir, 'task.md'),
    `---\n${yaml.dump(frontmatter, { lineWidth: 120 })}---\n\n${body}\n`,
    'utf-8',
  );

  // environment/
  await fs.mkdir(path.join(outDir, 'environment'), { recursive: true });
  if (skillsDir) {
    await copyDir(skillsDir, path.join(outDir, 'environment', 'skills'));
  } else {
    warnings.push('no skills directory found (task-level environment/skills or suite-level skills/) — exported package has no skills');
  }
  if (hasWorkspaceSeed) {
    await copyDir(workspaceSeed, path.join(outDir, 'environment', 'workspace'));
  }
  if (await isFile(ownDockerfile)) {
    await fs.copyFile(ownDockerfile, path.join(outDir, 'environment', 'Dockerfile'));
  } else {
    await fs.writeFile(path.join(outDir, 'environment', 'Dockerfile'), DOCKERFILE_STUB(hasWorkspaceSeed), 'utf-8');
  }

  // verifier/
  const outVerifierDir = path.join(outDir, 'verifier');
  await fs.mkdir(outVerifierDir, { recursive: true });
  if (verifierScript) {
    const scriptName = path.basename(verifierScript);
    if (scriptName === 'test.sh') {
      await fs.copyFile(verifierScript, path.join(outVerifierDir, 'test.sh'));
    } else {
      const interpreter = wrapperInterpreter(scriptName);
      if (!interpreter) {
        throw new Error(`Cannot export verifier ${scriptName}: no container interpreter for its extension (supported: .mjs, .js, .py, .sh).`);
      }
      await fs.copyFile(verifierScript, path.join(outVerifierDir, scriptName));
      await fs.writeFile(path.join(outVerifierDir, 'test.sh'), buildShWrapper('verifier', interpreter, scriptName), 'utf-8');
    }
    // Bring along any auxiliary verifier files (helpers, fixtures).
    const srcVerifierDir = path.join(taskDir, 'verifier');
    for (const entry of await fs.readdir(srcVerifierDir, { withFileTypes: true })) {
      const dest = path.join(outVerifierDir, entry.name);
      if (await isFile(dest) || await isDirectory(dest)) continue;
      const src = path.join(srcVerifierDir, entry.name);
      if (entry.isDirectory()) await copyDir(src, dest);
      else await fs.copyFile(src, dest);
    }
  } else if (checks && Object.keys(checks).length > 0) {
    // Lite-checks-only task: compile portable checks into a generated verifier.
    await fs.writeFile(path.join(outVerifierDir, 'checks.mjs'), buildChecksMjs(checks), 'utf-8');
    await fs.writeFile(path.join(outVerifierDir, 'test.sh'), buildShWrapper('verifier', 'node', 'checks.mjs'), 'utf-8');
    warnings.push('lite-checks task: generated verifier/checks.mjs runs output-text and files_exist checks; the harness must supply the agent output via SKILLJACK_OUTPUT_FILE (or /logs/agent/output.txt) for text checks to be meaningful');
  } else {
    warnings.push('task has neither a verifier script nor checks — exported verifier/test.sh always rewards 0');
    await fs.writeFile(
      path.join(outVerifierDir, 'test.sh'),
      '#!/bin/bash\n# Generated by skilljack-evals export — source task had no verifier or checks.\nmkdir -p /logs/verifier\necho 0 > /logs/verifier/reward.txt\n',
      'utf-8',
    );
  }

  // oracle/
  if (oracleScript) {
    const outOracleDir = path.join(outDir, 'oracle');
    await fs.mkdir(outOracleDir, { recursive: true });
    const scriptName = path.basename(oracleScript);
    if (scriptName === 'solve.sh') {
      await fs.copyFile(oracleScript, path.join(outOracleDir, 'solve.sh'));
    } else {
      const interpreter = wrapperInterpreter(scriptName);
      if (interpreter) {
        await fs.copyFile(oracleScript, path.join(outOracleDir, scriptName));
        await fs.writeFile(path.join(outOracleDir, 'solve.sh'), buildShWrapper('oracle', interpreter, scriptName), 'utf-8');
      } else {
        warnings.push(`oracle ${scriptName} has no container interpreter — copied without a solve.sh wrapper`);
        await fs.copyFile(oracleScript, path.join(outOracleDir, scriptName));
      }
    }
  }

  return { outDir, warnings };
}
